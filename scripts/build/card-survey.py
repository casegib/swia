#!/usr/bin/env python3
"""Regenerate docs/CARD_SURVEY.md from docs/cards/*.json.

docs/cards/*.json are the source of truth for every non-class-card family
(deployment cards, item deck, agenda cards, hero sheets, companions, form
cards), transcribed from the lvisintini/imperial-assault-data scans at 2x
with an icon legend and verified card-by-card. Edit the JSON, re-run this.
Class cards live in docs/class-cards.json (see class-card-survey.py).
"""
import json, collections, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
D = ROOT / "docs/cards"
load = lambda n: json.load(open(D / f"{n}.json", encoding="utf-8"))
dep, items, agenda, heroes, comp, forms = (load(n) for n in ("deployment-cards", "item-cards", "agenda-cards", "hero-sheets", "companion-cards", "form-cards"))
out = []; w = out.append
w("# Card Survey — deployment, items, agendas, heroes, companions, forms\n")
w("Every non-mission card family in `lvisintini/imperial-assault-data` (MIT-licensed metadata + scans; card content © LFL/FFG), transcribed at 2× against an icon legend and then verified card-by-card in a second independent read. Command cards (skirmish) are excluded by decision. Source of truth is `docs/cards/*.json`; this file is generated by `scripts/build/card-survey.py`. Class cards are in `docs/class-cards.json`.\n")
w("Notation: ⚡ surge · ✦ strain · ⊠ damage · [Block] · [Evade] · [Dodge] · ◆ threat · ⟶ action · [melee] / [ranged] · [Str]/[Ins]/[Tech] · [damage token] etc.\n")
w("## Census\n")
figs = [c for c in dep if c["kind"] == "figure"]; sk = [c for c in dep if c["kind"] != "figure"]
w("| Family | Cards | Becomes in Foundry |\n|---|---|---|")
w(f"| Deployment cards — figures | {len(figs)} | villain / ally actors with full stats |")
w(f"| Deployment cards — skirmish upgrades | {len(sk)} | not imported (skirmish only) |")
kinds = collections.Counter(c["kind"] for c in items)
w(f"| Item deck (upgrade {sum(1 for c in items if c['family']=='upgrade')} · supply {sum(1 for c in items if c['family']=='supply')} · reward {sum(1 for c in items if c['family']=='reward')}) | {len(items)} | weapon {kinds['weapon']} · armor {kinds['armor']} · weaponmod {kinds['weaponmod']} · gear {kinds['gear']} · feat (text) {kinds['feat']} |")
w(f"| Agenda cards | {len(agenda)} | `agendacard` items ({sum(1 for c in agenda if c['mission'])} mission-spawning, flagged) |")
w(f"| Hero sheets | {len(heroes)} | hero templates (healthy + wounded sides) |")
w(f"| Companions | {len(comp)} | companion actors |")
w(f"| Form cards | {len(forms)} | `formcard` items |")
w(f"| **Total** | **{len(dep)+len(items)+len(agenda)+len(heroes)+len(comp)+len(forms)}** | |\n")
w("## Deployment figures\n")
w("| Affiliation | Groups | Elite | Unique | Campaign-usable |\n|---|---|---|---|---|")
for aff in sorted(set(c["affiliation"] for c in figs)):
    s = [c for c in figs if c["affiliation"] == aff]
    w(f"| {aff} | {len(s)} | {sum(1 for c in s if c['elite'])} | {sum(1 for c in s if c['unique'])} | {sum(1 for c in s if 'Campaign' in c['modes'])} |")
w("\nPer figure the JSON carries: threat cost, reinforce cost, group size, health, speed, defense dice, attack type + dice, keyword line, surge abilities (cost + text), named abilities, traits, modes. Three figures have variable attacks (C-3PO none; IG-88 and General Weiss print '?' dice) — see `notes`.\n")
w("Attack types: " + ", ".join(f"{k or 'none'} {v}" for k, v in collections.Counter(c['attack']['type'] for c in figs).most_common()) + ".\n")
w("## Item deck\n")
w("| Tier | Cards | Weapons | Armor | Mods | Gear |\n|---|---|---|---|---|---|")
for tier in (1, 2, 3):
    s = [c for c in items if c.get("tier") == tier]
    k = collections.Counter(c["kind"] for c in s)
    w(f"| {tier} | {len(s)} | {k['weapon']} | {k['armor']} | {k['weaponmod']} | {k['gear']} |")
rw = [c for c in items if c["family"] == "reward"]
w(f"\nSupply: {sum(1 for c in items if c['family']=='supply')} gear cards. Rewards: {len(rw)} — shapes " + ", ".join(f"{k} {v}" for k, v in collections.Counter(c.get('shape') for c in rw).most_common()) + " (same four-shape classification as class cards; equipment rewards are weapons/armor/gear).\n")
w("## Agenda decks\n")
w("| Deck | Cards | Mission |\n|---|---|---|")
for deck in sorted(set(c["deck"] or "" for c in agenda)):
    s = [c for c in agenda if (c["deck"] or "") == deck]
    w(f"| {deck or '(unknown)'} | {len(s)} | {sum(1 for c in s if c['mission'])} |")
w("\n## Heroes\n")
w("| Hero | Health | Endurance | Speed | Defense | Strength | Insight | Tech |\n|---|---|---|---|---|---|---|---|")
dice = lambda d: " ".join(f"{n}{c[0]}" for c, n in d.items() if n) or "—"
for h in sorted(heroes, key=lambda x: x["name"]):
    s = h["healthy"]; wd = h["wounded"]
    w(f"| {h['name']} | {s['health']} / {wd['health']} | {s['endurance']} / {wd['endurance']} | {s['speed']} / {wd['speed']} | {dice(s['defense'])} | {dice(s['strength'])} | {dice(s['insight'])} | {dice(s['tech'])} |")
w("\n(healthy / wounded; dice as count + colour initial: 1b 1g 1y = blue, green, yellow.)\n")
w("## Verification\n")
w("Second-pass verification corrected: deployment 5 of 161 (an affiliation, a keyword, a phantom ability, a Dodge/Block glyph), items 3 of 154 (formatting/name), agendas 38 of 114 (all formatting — a duplicated timing sentence and deck-name apostrophes; no rules changes), heroes 1 of 19 (Vinto's wounded Insight pool), companions and forms 0. Corrected cards carry `verified_note`.\n")
w("## Next step\n")
w("The compendium generator (backlog: Class cards → Compendium generator) reads these files plus `docs/class-cards.json` and emits `packs/_source/` documents: deployment figures → villain/ally actors; item deck → weapon/armor/weaponmod/gear items with dice and surge lines parsed; agendas → `agendacard` items; hero sheets → `herotemplate` items for the hero builder; companions → companion actors; form cards → `formcard` items. Card art is referenced from a local `assets/cards/` folder the GM populates from the dataset, not committed.\n")
(ROOT / "docs/CARD_SURVEY.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote docs/CARD_SURVEY.md")
